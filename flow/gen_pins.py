#!/usr/bin/env python3
# gen_pins.py - Choose core-block pin locations facing their frame pads; write OpenROAD place_pin Tcl.
# Usage: python3 flow/gen_pins.py <padmap.json> <edge_pins.json> <out_pins.tcl>
# edge_pins.json comes from flow/edge_pins.py (frame nets reaching the ring's inner edge).
import json, sys

padmap = json.load(open(sys.argv[1]))           # Design pad map
edges = json.load(open(sys.argv[2]))            # Frame edge pins
out = sys.argv[3]                               # Output Tcl

ox, oy = padmap["core_origin"]                  # Core block lower-left in frame coords
W, H = padmap["die_size"]                       # Core block size
lo, hi = padmap["pin_span"]                     # Usable span along each core edge (local)
CLEAR = 25.0                                    # Keep pins this far from power straps / pad lines
GRID = 0.1                                      # Pin snap (manufacturing grid is 0.005)

def pad_point(net):
    """Return (side, coord along the edge in frame coords) of a frame net's inner-edge stub."""
    side, layer, x1, y1, x2, y2 = edges[net][0]
    return side, ((x1 + x2) / 2 if side in "SN" else (y1 + y2) / 2)

# Coordinates along each side that pins must avoid: every pad stub, plus power stripes on W/E
avoid = {"S": [], "N": [], "W": [], "E": []}
for net, rects in edges.items():
    for side, layer, x1, y1, x2, y2 in rects:
        avoid[side].append(((x1 + x2) / 2) if side in "SN" else ((y1 + y2) / 2))
for k, p in padmap["power"].items():
    if k.startswith("_"): continue
    avoid["W"].append(p["stripe_y_frame"]); avoid["E"].append(p["stripe_y_frame"])

# Range of pad stubs along a side, taken from the frame itself (3 mm frame: 521 .. 2642.5)
_all = [((x1 + x2) / 2 if s in "SN" else (y1 + y2) / 2) for r in edges.values() for s, _, x1, y1, x2, y2 in r]
pad_min, pad_max = min(_all), max(_all)

by_side = {"S": [], "N": [], "W": [], "E": []}  # side -> [(pad coord, port)]
for port, net in padmap["pins"].items():
    s, c = pad_point(net)
    by_side[s].append((c, port))

pins = []                                       # (port, side, local coord)
for s, lst in by_side.items():
    lst.sort()
    base = ox if s in "SN" else oy              # Frame offset along this side

    span_f = (base + lo, base + hi)             # Pin span in frame coords
    used = []
    for c, port in lst:
        t = span_f[0] + (c - pad_min) / (pad_max - pad_min) * (span_f[1] - span_f[0])  # Proportional map
        step, k = 0.0, 0
        while True:                             # Nudge until clear of pads, stripes and other pins
            cand = round((t + step) / GRID) * GRID
            ok = span_f[0] <= cand <= span_f[1] and all(abs(cand - a) >= CLEAR for a in avoid[s] + used)
            if ok:
                break
            k += 1
            step = (k // 2 + 1) * 5.0 * (1 if k % 2 else -1)
        used.append(cand)
        pins.append((port, s, cand - base))

with open(out, "w") as f:
    f.write("# Generated by flow/gen_pins.py - core pin locations (core-local um)\n")
    for port, s, c in pins:
        if s == "S":   loc, layer, size = (c, 0.0), "metal2", "3 6"
        elif s == "N": loc, layer, size = (c, H), "metal2", "3 6"
        elif s == "W": loc, layer, size = (0.0, c), "metal1", "6 3"
        else:          loc, layer, size = (W, c), "metal1", "6 3"
        f.write("place_pin -pin_name {%s} -layer %s -location {%.3f %.3f} -pin_size {%s} -force_to_die_boundary\n"
                % (port, layer, loc[0], loc[1], size))
        print("%-11s %s %8.2f (frame %8.2f)" % (port, s, c, c + (ox if s in "SN" else oy)))
